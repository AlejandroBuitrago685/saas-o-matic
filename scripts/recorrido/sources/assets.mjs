/**
 * The visual assets the walkthrough shares with the application (D-183): its design tokens, its self-hosted font and
 * the size of each screenshot of `docs/capturas`.
 */

export const TOKENS_FILE = 'apps/web/src/styles/tokens.css';
export const FONT_DIR = 'node_modules/@fontsource-variable/montserrat';
export const FONT_FILE = 'files/montserrat-latin-wght-normal.woff2';

/**
 * @param {string} tokens the text of the application's tokens.css
 * @returns {string} a stylesheet with the same colours, radii and shadows as custom properties of `:root`, so the
 * page cannot drift from the application (their contrast is tested by tools/design-tokens.test.ts)
 */
export function tokenStylesheet(tokens) {
  const declarations = [...tokens.matchAll(/^\s*(--(?:color|radius|shadow)-[a-z0-9-]+):\s*([^;]+);/gm)]
    .filter(([, , value]) => value !== 'initial')
    .map(([, name, value]) => `  ${name ?? ''}: ${value ?? ''};`);
  if (declarations.length === 0) throw new Error('tokenStylesheet: no colour tokens found');
  return [
    `/* Generated by \`npm run recorrido\` from ${TOKENS_FILE}: do not edit (D-183). */`,
    ':root {',
    ...declarations,
    '}',
    '',
  ].join('\n');
}

/**
 * @param {Uint8Array} bytes a WebP file
 * @returns {{ width: number, height: number }} its size in pixels, from the header of its first chunk
 */
export function webpSize(bytes) {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const text = (/** @type {number} */ start, /** @type {number} */ length) =>
    String.fromCharCode(...bytes.subarray(start, start + length));
  if (text(0, 4) !== 'RIFF' || text(8, 4) !== 'WEBP') throw new Error('webpSize: not a WebP file');
  const chunk = text(12, 4);
  if (chunk === 'VP8 ')
    return { width: view.getUint16(26, true) & 0x3fff, height: view.getUint16(28, true) & 0x3fff };
  if (chunk === 'VP8L') {
    const bits = view.getUint32(21, true);
    return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 };
  }
  if (chunk === 'VP8X') {
    const read24 = (/** @type {number} */ at) => view.getUint16(at, true) + (view.getUint8(at + 2) << 16) + 1;
    return { width: read24(24), height: read24(27) };
  }
  throw new Error(`webpSize: unknown chunk ${chunk}`);
}
